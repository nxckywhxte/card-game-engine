package org.nxckywhxte.cardgame.api;

import org.nxckywhxte.cardgame.api.exception.CardNotFoundException;
import org.nxckywhxte.cardgame.core.Card;

/**
 * Игрок карточной игры.
 *
 * <p>Игрок представляет участника игры с уникальным идентификатором, именем и рукой карт. Рука
 * игрока является {@link Zone}, что позволяет использовать все операции зон для работы с картами
 * игрока.
 *
 * <h2>Иммутабельность</h2>
 *
 * <p>Игрок является <b>полностью неизменяемым</b>. Все операции, которые "изменяют" игрока
 * (добавление или удаление карт из руки), возвращают <b>новые</b> экземпляры игрока, не изменяя
 * исходный. Это критично для реализации отмены ходов, симуляций и сетевой игры.
 *
 * <h2>Идентификация</h2>
 *
 * <p>Каждый игрок имеет уникальный идентификатор ({@link #getId()}), который используется для
 * различения игроков в коллекциях, сетевой игре и сериализации. Идентификатор не может быть {@code
 * null} или пустой строкой.
 *
 * <p>Имя игрока ({@link #getName()}) используется для отображения в интерфейсе. Два игрока могут
 * иметь одинаковое имя, но должны иметь разные идентификаторы.
 *
 * <h2>Инварианты</h2>
 *
 * <p>Следующие условия всегда истинны для любой реализации {@code Player}:
 *
 * <ul>
 *   <li>{@code getId() != null && !getId().isEmpty()}
 *   <li>{@code getName() != null}
 *   <li>{@code getHand() != null}
 *   <li>{@code handSize() == getHand().size()}
 *   <li>{@code hasCards() == (handSize() > 0)}
 *   <li>{@code withHand(zone).getHand() == zone} (новая рука становится текущей)
 * </ul>
 *
 * <p>Пример использования:
 *
 * <pre>{@code
 * Player player = PlayerFactory.create("player-1", "Alice");
 * Player updated = player.addToHand(card);
 * boolean hasCards = updated.hasCards();
 * }</pre>
 *
 * <h2>Потокобезопасность</h2>
 *
 * <p>Поскольку игрок неизменяем, он потокобезопасен: его можно безопасно передавать между потоками
 * без синхронизации.
 *
 * @author nxckywhxte
 * @since 0.0.1
 * @see Zone
 * @see Card
 */
public interface Player {
  /**
   * Возвращает уникальный идентификатор игрока.
   *
   * <p>Идентификатор используется для различения игроков в коллекциях, сетевой игре и сериализации.
   * Он не может быть {@code null} или пустым.
   *
   * <p>Два игрока считаются одинаковыми, если их идентификаторы равны.
   *
   * @return уникальный идентификатор игрока
   */
  String getId();

  /**
   * Возвращает имя игрока для отображения.
   *
   * <p>Имя используется в пользовательском интерфейсе. В отличие от идентификатора, два игрока
   * могут иметь одинаковое имя.
   *
   * @return имя игрока
   */
  String getName();

  /**
   * Возвращает руку игрока — зону, содержащую карты игрока.
   *
   * <p>Возвращённая зона является неизменяемой. Для изменения руки используйте методы {@link
   * #addToHand(Card)} и {@link #removeFromHand(Card)}, которые возвращают нового игрока.
   *
   * @return рука игрока (неизменяемая зона)
   */
  Zone getHand();

  /**
   * Возвращает количество карт в руке игрока.
   *
   * @return количество карт в руке
   */
  int handSize();

  /**
   * Проверяет, есть ли у игрока карты в руке.
   *
   * <p>Во многих играх игрок без карт считается победителем или выбывшим.
   *
   * @return {@code true}, если у игрока есть карты
   */
  boolean hasCards();

  /**
   * Добавляет карту в руку игрока.
   *
   * <p>Возвращает <b>нового</b> игрока с обновлённой рукой. Исходный игрок не изменяется.
   *
   * @param card карта для добавления
   * @return новый игрок с добавленной картой в руке
   * @throws IllegalArgumentException если {@code card == null}
   */
  Player addToHand(Card card);

  /**
   * Удаляет карту из руки игрока.
   *
   * <p>Возвращает <b>нового</b> игрока без указанной карты в руке. Исходный игрок не изменяется.
   *
   * @param card карта для удаления
   * @return новый игрок без удалённой карты в руке
   * @throws CardNotFoundException если карты нет в руке
   * @throws IllegalArgumentException если {@code card == null}
   */
  Player removeFromHand(Card card);

  /**
   * Возвращает нового игрока с полностью заменённой рукой.
   *
   * <p>Полезно для операций массовой замены руки:
   *
   * <ul>
   *   <li>Раздать новую руку из колоды
   *   <li>Очистить руку (передать пустую зону)
   *   <li>Симуляция альтернативных состояний игры
   * </ul>
   *
   * <p>Возвращает <b>нового</b> игрока с новой рукой. Исходный игрок не изменяется.
   *
   * <p>Пример использования:
   *
   * <pre>{@code
   * Zone newHand = ZoneFactory.of(dealtCards);
   * Player updated = player.withHand(newHand);
   * }</pre>
   *
   * @param newHand новая рука игрока
   * @return новый игрок с указанной рукой
   * @throws IllegalArgumentException если {@code newHand == null}
   */
  Player withHand(Zone newHand);
}
