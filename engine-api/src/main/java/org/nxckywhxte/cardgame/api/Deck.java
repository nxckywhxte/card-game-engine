package org.nxckywhxte.cardgame.api;

import java.util.List;
import org.nxckywhxte.cardgame.core.Card;

/**
 * Колода игральных карт.
 *
 * <p>Колода является неизменяемым контейнером карт. Все операции, которые "изменяют" колоду
 * (например, тасование), возвращают <b>новый</b> экземпляр колоды, не изменяя исходный.
 *
 * <p>Пример использования:
 *
 * <pre>{@code
 * Deck deck = DeckFactory.standard52(); // 52 карты
 * Deck shuffled = deck.shuffle(); // новая перетасованная колода
 * Card card = shuffled.draw(); // взять верхнюю карту
 * }</pre>
 *
 * @author nxckywhxte
 * @since 0.0.1
 * @see Card
 */
public interface Deck {
  /**
   * Возвращает общее количество карт в колоде.
   *
   * <p>Это значение постоянно после создания колоды и не зависит от того, сколько карт уже взято.
   *
   * @return общее количество карт
   */
  int size();

  /**
   * Возвращает количество оставшихся карт в колоде.
   *
   * @return количество карт, которые ещё можно взять
   */
  int remaining();

  /**
   * Проверяет, пуста ли колода.
   *
   * @return {@code true}, если в колоде не осталось карт
   */
  boolean isEmpty();

  /**
   * Берёт верхнюю карту из колоды.
   *
   * <p>После взятия карты она удаляется из колоды. Если колода пуста, бросается {@link
   * EmptyDeckException}.
   *
   * @return верхняя карта колоды
   * @throws EmptyDeckException если колода пуста
   */
  Card draw();

  /**
   * Берёт указанное количество карт из колоды.
   *
   * <p>Удобно для раздачи карт игрокам. Если в колоде недостаточно карт, бросается {@link
   * EmptyDeckException}.
   *
   * @param count количество карт для взятия
   * @return список взятых карт в порядке взятия
   * @throws IllegalArgumentException если count <= 0
   * @throws EmptyDeckException если в колоде недостаточно карт
   */
  List<Card> drawMany(int count);

  /**
   * Перетасовывает колоду.
   *
   * <p>Возвращает <b>новую</b> колоду с тем же набором карт, но в случайном порядке. Исходная
   * колода не изменяется.
   *
   * @return новая перетасованная колода
   */
  Deck shuffle();

  /**
   * Перетасовывает колоду с использованием указанного генератора случайных чисел.
   *
   * <p>Полезно для детерминированного тестирования: можно передать {@link java.util.Random} с
   * фиксированным seed и получить предсказуемый порядок карт.
   *
   * @param random генератор случайных чисел
   * @return новая перетасованная колода
   * @throws IllegalArgumentException если random == null
   */
  Deck shuffle(java.util.Random random);

  /**
   * Показывает верхние карты колоды, не вынимая их.
   *
   * <p>Полезно для некоторых игр, где нужно знать следующие карты (например, в Клондайке можно
   * видеть верхнюю карту колоды).
   *
   * @param count количество карт для просмотра
   * @return список верхних карт (без их удаления из колоды)
   * @throws IllegalArgumentException если count <= 0
   * @throws EmptyDeckException если в колоде недостаточно карт
   */
  List<Card> peek(int count);
}
