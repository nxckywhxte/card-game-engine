package org.nxckywhxte.cardgame.api;

import java.util.List;
import java.util.Optional;
import java.util.Random;
import org.nxckywhxte.cardgame.api.exception.EmptyDeckException;
import org.nxckywhxte.cardgame.core.Card;

/**
 * Колода игральных карт.
 *
 * <p>Колода является <b>полностью неизменяемым</b> контейнером карт. Все операции, которые
 * "изменяют" колоду (взятие карт, тасование), возвращают <b>новые</b> экземпляры, не изменяя
 * исходный.
 *
 * <h2>Иммутабельность</h2>
 *
 * <p>Иммутабельность критична для игровой библиотеки, так как позволяет:
 *
 * <ul>
 *   <li>Реализовать отмену ходов (undo) через сохранение состояний
 *   <li>Проводить симуляции нескольких вариантов ходов параллельно
 *   <li>Безопасно передавать состояния в сетевой игре
 *   <li>Сериализовать состояние игры в любой момент
 * </ul>
 *
 * <h2>Инварианты</h2>
 *
 * <p>Следующие условия всегда истинны для любой реализации {@code Deck}:
 *
 * <ul>
 *   <li>{@code 0 <= remaining() <= size()}
 *   <li>{@code isEmpty() == true} тогда и только тогда, когда {@code remaining() == 0}
 *   <li>{@code draw()} уменьшает {@code remaining()} на 1
 *   <li>{@code drawMany(n)} уменьшает {@code remaining()} на {@code n}
 *   <li>{@code shuffle()} сохраняет {@code remaining()} без изменений
 *   <li>{@code peek()} и {@code peekMany()} не изменяют {@code remaining()}
 * </ul>
 *
 * <p>Пример использования:
 *
 * <pre>{@code
 * Deck deck = DeckFactory.standard52().shuffle();
 * DrawResult result = deck.draw();
 * Card card = result.firstCard();
 * Deck remaining = result.deck();
 * }</pre>
 *
 * <h2>Потокобезопасность</h2>
 *
 * <p>Поскольку колода неизменяема, она потокобезопасна: её можно безопасно передавать между
 * потоками без синхронизации.
 *
 * @author nxckywhxte
 * @since 0.0.1
 * @see Card
 * @see DrawResult
 * @see EmptyDeckException
 */
public interface Deck {

  /**
   * Возвращает общее количество карт в колоде.
   *
   * <p>Это значение постоянно после создания колоды и не зависит от того, сколько карт уже взято.
   *
   * @return общее количество карт
   */
  int size();

  /**
   * Возвращает количество оставшихся карт в колоде.
   *
   * @return количество карт, которые ещё можно взять
   */
  int remaining();

  /**
   * Проверяет, пуста ли колода.
   *
   * @return {@code true}, если в колоде не осталось карт
   */
  boolean isEmpty();

  /**
   * Берёт верхнюю карту из колоды.
   *
   * <p>Возвращает {@link DrawResult}, содержащий взятую карту и новую колоду без этой карты.
   * Исходная колода не изменяется.
   *
   * @return результат взятия: карта и новая колода
   * @throws EmptyDeckException если колода пуста
   */
  DrawResult draw();

  /**
   * Пытается взять верхнюю карту, не бросая исключение.
   *
   * <p>Этот метод предпочтителен, когда пустая колода является ожидаемой частью игрового процесса.
   *
   * @return {@link Optional} с {@link DrawResult} или пустой, если колода пуста
   */
  Optional<DrawResult> tryDraw();

  /**
   * Берёт указанное количество карт из колоды.
   *
   * <p>Удобно для раздачи карт игрокам.
   *
   * @param count количество карт для взятия
   * @return результат взятия: список карт и новая колода
   * @throws IllegalArgumentException если {@code count <= 0}
   * @throws EmptyDeckException если в колоде недостаточно карт
   */
  DrawResult drawMany(int count);

  /**
   * Показывает верхнюю карту колоды, не вынимая её.
   *
   * @return верхняя карта
   * @throws EmptyDeckException если колода пуста
   */
  Card peek();

  /**
   * Пытается посмотреть верхнюю карту, не бросая исключение.
   *
   * @return {@link Optional} с верхней картой или пустой, если колода пуста
   */
  Optional<Card> tryPeek();

  /**
   * Показывает указанное количество верхних карт, не вынимая их.
   *
   * <p>Возвращаемый список упорядочен от верха колоды к низу.
   *
   * @param count количество карт для просмотра
   * @return неизменяемый список верхних карт в порядке от верха к низу
   * @throws IllegalArgumentException если {@code count <= 0}
   * @throws EmptyDeckException если в колоде недостаточно карт
   */
  List<Card> peekMany(int count);

  /**
   * Перетасовывает колоду.
   *
   * <p>Возвращает <b>новую</b> колоду с тем же набором карт в случайном порядке. Исходная колода не
   * изменяется.
   *
   * @return новая перетасованная колода
   */
  Deck shuffle();

  /**
   * Перетасовывает колоду с использованием указанного генератора случайных чисел.
   *
   * <p>Полезно для детерминированного тестирования: можно передать {@link Random} с фиксированным
   * seed и получить предсказуемый порядок карт.
   *
   * @param random генератор случайных чисел
   * @return новая перетасованная колода
   * @throws IllegalArgumentException если {@code random == null}
   */
  Deck shuffle(Random random);

  /**
   * Возвращает неизменяемый список оставшихся карт от верха к низу.
   *
   * <p>Полезно для сериализации состояния, отладки и тестирования. Возвращённый список является
   * копией и не влияет на колоду. Попытка изменить возвращённый список бросит {@link
   * UnsupportedOperationException}.
   *
   * @return неизменяемый список оставшихся карт
   */
  List<Card> remainingCards();

  /**
   * Проверяет, содержится ли карта в колоде.
   *
   * @param card карта для поиска
   * @return {@code true}, если карта есть в колоде
   */
  boolean contains(Card card);
}
